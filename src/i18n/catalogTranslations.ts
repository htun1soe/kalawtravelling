export function localizeModalItem(item: ModalItem, lang: Language): ModalItem {
  if (lang === 'en') return item;
  switch (item.kind) {
    case 'destination':
      return { kind: 'destination', data: localizeDestination(item.data, lang) };
    case 'stay':
      return { kind: 'stay', data: localizeStay(item.data, lang) };
    case 'experience':
      return { kind: 'experience', data: localizeExperience(item.data, lang) };
    case 'restaurant':
      return { kind: 'restaurant', data: localizeRestaurant(item.data, lang) };
    case 'rental':
      return { kind: 'rental', data: localizeRental(item.data, lang) };
    case 'property':
      return { kind: 'property', data: localizeProperty(item.data, lang) };
    case 'article':
      return { kind: 'article', data: localizeArticle(item.data, lang) };
  }
}
