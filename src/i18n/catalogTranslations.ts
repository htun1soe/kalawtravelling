function applyMediaCaptions(media: MediaItem[] | undefined, captions?: string[]): MediaItem[] | undefined {
  if (!media || !captions || captions.length === 0) return media;
  return media.map((m, idx) => (captions[idx] ? { ...m, caption: captions[idx] } : m));
}

export function localizeDestination(item: Destination, lang: Language): Destination {
  if (lang === 'en' || !DEST_MY[item.id]) return item;
  const { mediaCaptions, ...fields } = DEST_MY[item.id];
  return {
    ...item,
    ...fields,
    media: applyMediaCaptions(item.media, mediaCaptions),
  };
}

